/*
 * Bundles the moodpage engine from the repository root into one HTML string
 * the app can hand to a WebView: the stylesheet, today's mood.js as the
 * default weather, the engine scripts, and the host bridge, all inline, so
 * the weather runs offline and never loads anything from the network. log.js
 * goes first, so even an engine that fails to load is heard.
 *
 * Writes src/engine/engine-html.ts (generated, not committed). Runs on
 * install and before every start.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, "..");
const root = path.resolve(app, "..");

const SCRIPTS = [
  "mood.js",
  "shader.js",
  "interaction.js",
  "app.js",
  "motes.js",
  "realtime.js",
  "sound.js",
  "moodpage.js",
];

const read = (file) => fs.readFileSync(file, "utf8");
// Inline scripts must not close their own tag.
const inline = (code) => code.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover" />
<meta name="color-scheme" content="dark" />
<style>
${read(path.join(root, "styles.css"))}
</style>
</head>
<body>
<main class="stage moodpage"></main>
<script>
${inline(read(path.join(app, "src/engine/log.js")))}
</script>
<script>window.__MOODPAGE_MOOD = /*__MOOD__*/null; window.__MOODPAGE_ROOM = /*__ROOM__*/null;</script>
${SCRIPTS.map((file) => `<script>\n${inline(read(path.join(root, file)))}\n</script>`).join("\n")}
<script>
${inline(read(path.join(app, "src/engine/host.js")))}
</script>
</body>
</html>
`;

const out = path.join(app, "src/engine/engine-html.ts");
fs.writeFileSync(
  out,
  "// Generated by scripts/build-engine.mjs from the repository root. Do not edit.\n" +
    "export const ENGINE_HTML = " +
    JSON.stringify(html) +
    ";\n",
);
console.log("engine → " + path.relative(app, out) + " (" + Math.round(html.length / 1024) + " KB)");
